"""Task 13: LLM-as-judge evaluation of the full agent on 15 queries (MOCK_LLM).

Every query goes through the real pipeline (guardrails -> memory -> CrewAI crew -> output guard). The
rendered eval/judge_prompt.txt is sent to the judge LLM (MockJudgeLLM under MOCK_LLM), which returns
accuracy / grounding / completeness / safety in [0, 1].

Outputs: eval/results.json, eval/results.md, transcripts/task13_evaluation.txt
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import config  # noqa: E402
from demos._transcript import transcript  # noqa: E402
from ola_agent.memory import ask  # noqa: E402
from ola_agent.rag.index import build_index  # noqa: E402
from ola_agent.rag.kb import REQUIRED_TOPICS  # noqa: E402

EVAL_DIR = ROOT / "eval"
METRICS = ("accuracy", "grounding", "completeness", "safety")


def get_judge():
    if not config.MOCK_LLM:
        raise NotImplementedError("Real-LLM judge is optional and not configured; run with MOCK_LLM=1.")
    from ola_agent.llm.mock_judge import MockJudgeLLM

    return MockJudgeLLM()


def render_prompt(template: str, case: dict, result) -> str:
    ctx_lines = [f"[{c['doc_id']}] {c['text']}" for c in result.context]
    if result.lookup:
        ctx_lines.append("TICKET RECORD: " + json.dumps(result.lookup))
    key_points = "\n".join(f"- {p}" for p in case["key_points"]) or "(none)"
    return (template.replace("{query}", case["query"])
            .replace("{expected_behavior}", case["expected_behavior"])
            .replace("{key_points}", key_points)
            .replace("{context}", "\n".join(ctx_lines) or "(no context retrieved)")
            .replace("{answer}", result.response.answer))


def main() -> dict:
    build_index()
    cases = json.loads((EVAL_DIR / "testset.json").read_text(encoding="utf-8"))
    template = (EVAL_DIR / "judge_prompt.txt").read_text(encoding="utf-8")
    judge = get_judge()

    assert len(cases) == 15, len(cases)
    covered = {c["doc_id"] for c in cases if c["doc_id"]}
    assert set(REQUIRED_TOPICS.values()) <= covered, "every required KB topic needs a query"
    assert sum(c["expected_behavior"] != "answer" for c in cases) >= 2, "need >= 2 out-of-scope/edge queries"

    rows = []
    with transcript("task13_evaluation"):
        print(f"LLM-as-judge evaluation | MOCK_LLM={config.MOCK_LLM} | judge={judge.model_name} | 15 queries")
        print(f"All 12 required KB topics covered: {set(REQUIRED_TOPICS.values()) <= covered} | "
              f"out-of-scope/edge queries: {sum(c['expected_behavior'] != 'answer' for c in cases)}\n")
        for case in cases:
            result = ask(case["query"], session_id=f"eval-{case['id']}")
            scores = json.loads(judge.complete(render_prompt(template, case, result)))
            rows.append({**case, "answer": result.response.answer, "intent": result.response.intent,
                         "guardrail_flags": result.response.guardrail_flags, **scores})
            print(f"{case['id']} [{case['topic']}] {case['query']}")
            print(f"    answer: {result.response.answer}")
            print(f"    flags : {result.response.guardrail_flags}")
            print("    scores: " + "  ".join(f"{m}={scores[m]:.2f}" for m in METRICS))
            print(f"    judge : {scores['rationale']}\n")

        averages = {m: round(sum(r[m] for r in rows) / len(rows), 3) for m in METRICS}
        header = f"| ID | Topic | {' | '.join(m.title() for m in METRICS)} |"
        table = [header, "|" + "---|" * (len(METRICS) + 2)]
        table += [f"| {r['id']} | {r['topic']} | " + " | ".join(f"{r[m]:.2f}" for m in METRICS) + " |" for r in rows]
        table.append("| **Avg** | **all 15** | " + " | ".join(f"**{averages[m]:.3f}**" for m in METRICS) + " |")
        print("\n".join(table))
        print(f"\nJudge LLM calls: {judge.call_count}")

    (EVAL_DIR / "results.json").write_text(json.dumps({"averages": averages, "rows": rows}, indent=2), encoding="utf-8")
    (EVAL_DIR / "results.md").write_text(
        "# Evaluation results (MOCK_LLM, LLM-as-judge)\n\nScores in [0, 1]. Generated by `python eval/run_eval.py`.\n\n"
        + "\n".join(table) + "\n", encoding="utf-8")
    return averages


if __name__ == "__main__":
    main()
